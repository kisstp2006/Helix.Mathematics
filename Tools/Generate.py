"""Generates the vector and matrix types of Helix.Mathematics, the math functions over them and Random.

Run from anywhere: python Tools/Generate.py. The output goes to Source/Helix.Mathematics/Generated/ (checked in).
"""
import itertools
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "Source" / "Helix.Mathematics" / "Generated"
HEADER = "// Generated by Tools/Generate.py; do not edit.\n"
C = "xyzw"
ELEMS = ["bool", "int", "uint", "float", "double"]
NUMERIC = ["int", "uint", "float", "double"]
REAL = ["float", "double"]
# The element types a type converts from (implicit ones; the others explicit), as the reference has them.
IMPLICIT = {"float": ["int", "uint", "half"], "double": ["int", "uint", "half", "float"], "int": [], "uint": [], "bool": []}
EXPLICIT = {"float": ["bool", "double"], "double": ["bool"], "int": ["bool", "uint", "float", "double"], "uint": ["bool", "int", "float", "double"],
            "bool": []}
SUFFIX = {"float": "f", "double": "", "int": "", "uint": "", "bool": ""}
ZERO = {"bool": "false", "int": "0", "uint": "0u", "float": "0.0f", "double": "0.0"}
ONE = {"int": "1", "uint": "1u", "float": "1.0f", "double": "1.0"}


def vt(e, n):
    return e if n == 1 else f"{e}{n}"


def mt(e, r, c):
    return f"{e}{r}x{c}"


def conv(src, dst, x):
    """C# expression converting the scalar x of type src to dst."""
    if src == dst:
        return x
    if src == "bool":
        return f"({x} ? {ONE[dst]} : {ZERO[dst]})"
    if src == "half":
        return f"({dst})(float){x}"
    return f"({dst}){x}"


def compositions(n):
    """The ways to build n components from parts of 1 to n components, in order."""
    if n == 0:
        return [[]]
    out = []
    for k in range(1, n + 1):
        for rest in compositions(n - k):
            out.append([k] + rest)
    return out


def hash_primes(name, count):
    """Odd constants per type (deterministic, from the type's name)."""
    h = 2166136261
    for ch in name:
        h = ((h ^ ord(ch)) * 16777619) & 0xFFFFFFFF
    out = []
    for i in range(count + 1):
        h = (h * 1103515245 + 12345 + i * 0x9E3779B9) & 0xFFFFFFFF
        out.append(h | 0x80000001)
    return out


class W:
    def __init__(self):
        self.lines = []
        self.depth = 0

    def __call__(self, text=""):
        for line in text.split("\n"):
            self.lines.append(("    " * self.depth + line) if line else "")

    def open(self, text):
        self(text)
        self("{")
        self.depth += 1

    def close(self, suffix=""):
        self.depth -= 1
        self("}" + suffix)

    def text(self):
        return "\n".join(self.lines) + "\n"


def write(name, body):
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(HEADER + body, encoding="utf-8", newline="\n")


