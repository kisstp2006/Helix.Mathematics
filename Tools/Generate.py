def random():
    w = W()
    w("using System;\nusing System.Runtime.CompilerServices;\nusing static Helix.Mathematics.math;\n\nnamespace Helix.Mathematics\n{")
    w.depth += 1
    w.open("public partial struct Random")
    for n in (2, 3, 4):
        w(f"/// <summary>A uniformly random int{n} in [-2147483648, 2147483647].</summary>")
        w(f"public int{n} NextInt{n}() => new int{n}({', '.join('(int)NextState()' for _ in range(n))}) ^ -2147483648;")
        w(f"public int{n} NextInt{n}(int{n} max) {{ {' '.join(f'CheckNextIntMax(max.{C[i]});' for i in range(n))} return new int{n}({', '.join(f'(int)((NextState() * (ulong)max.{C[i]}) >> 32)' for i in range(n))}); }}")
        w(f"public int{n} NextInt{n}(int{n} min, int{n} max) {{ {' '.join(f'CheckNextIntMinMax(min.{C[i]}, max.{C[i]});' for i in range(n))} var range = (uint{n})(max - min); return new int{n}({', '.join(f'(int)(NextState() * (ulong)range.{C[i]} >> 32)' for i in range(n))}) + min; }}")
        w(f"public uint{n} NextUInt{n}() => new uint{n}({', '.join('NextState()' for _ in range(n))}) - 1u;")
        w(f"public uint{n} NextUInt{n}(uint{n} max) => new uint{n}({', '.join(f'(uint)((NextState() * (ulong)max.{C[i]}) >> 32)' for i in range(n))});")
        w(f"public uint{n} NextUInt{n}(uint{n} min, uint{n} max) {{ {' '.join(f'CheckNextUIntMinMax(min.{C[i]}, max.{C[i]});' for i in range(n))} var range = max - min; return new uint{n}({', '.join(f'(uint)(NextState() * (ulong)range.{C[i]} >> 32)' for i in range(n))}) + min; }}")
        w(f"public float{n} NextFloat{n}() => asfloat(0x3f800000u | (new uint{n}({', '.join('NextState()' for _ in range(n))}) >> 9)) - 1.0f;")
        w(f"public float{n} NextFloat{n}(float{n} max) => NextFloat{n}() * max;")
        w(f"public float{n} NextFloat{n}(float{n} min, float{n} max) => NextFloat{n}() * (max - min) + min;")
        dvals = ", ".join("NextDoubleBits()" for _ in range(n))
        w(f"public double{n} NextDouble{n}() => new double{n}({dvals});")
        w(f"public double{n} NextDouble{n}(double{n} max) => NextDouble{n}() * max;")
        w(f"public double{n} NextDouble{n}(double{n} min, double{n} max) => NextDouble{n}() * (max - min) + min;")
    w.close()
    w.depth -= 1
    w("}")
    return w.text()


def main():
    ctor_functions = []
    for e in ELEMS:
        for n in (2, 3, 4):
            text, fns = vector(e, n)
            write(f"{vt(e, n)}.gen.cs", text)
            ctor_functions += fns
        for r in (2, 3, 4):
            for c in (2, 3, 4):
                text, fns = matrix(e, r, c)
                write(f"{mt(e, r, c)}.gen.cs", text)
                ctor_functions += fns
    for n in (2, 3, 4):
        text, fns = half_vector(n)
        write(f"half{n}.gen.cs", text)
        ctor_functions += fns
    body = W()
