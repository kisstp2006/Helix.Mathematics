def vector_ctors(e, n):
    """(parameter list, assignments) of every constructor of the vector type."""
    t = vt(e, n)
    out = []
    for parts in compositions(n):
        params, assigns, at = [], [], 0
        for i, k in enumerate(parts):
            p = C[at:at + k] if k > 1 else C[at]
            params.append(f"{vt(e, k)} {p}")
            if k == 1:
                assigns.append(f"this.{C[at]} = {p};")
            else:
                for j in range(k):
                    assigns.append(f"this.{C[at + j]} = {p}.{C[j]};")
            at += k
        out.append((", ".join(params), " ".join(assigns), "parts"))
    out.append((f"{e} v", " ".join(f"this.{c} = v;" for c in C[:n]), "scalar"))
    for src in IMPLICIT[e] + EXPLICIT[e]:
        out.append((f"{src} v", " ".join(f"this.{c} = {conv(src, e, 'v')};" for c in C[:n]), "scalar"))
        out.append((f"{vt(src, n)} v", " ".join(f"this.{c} = {conv(src, e, 'v.' + c)};" for c in C[:n]), "vector"))
    return out


def vector(e, n):
    t = vt(e, n)
    w = W()
    w("using System;\nusing System.ComponentModel;\nusing System.Runtime.CompilerServices;\n\nnamespace Helix.Mathematics\n{")
    w.depth += 1
    ifaces = f"IEquatable<{t}>" + ("" if e == "bool" else ", IFormattable")
    w(f"/// <summary>A {n} component vector of {e} values.</summary>")
    w("[Serializable]")
    w.open(f"public partial struct {t} : {ifaces}")
    w(f"public {e} {', '.join(C[:n])};")
    w()
    if e != "bool":
        w(f"/// <summary>All components zero.</summary>")
        w(f"public static readonly {t} zero;")
        w()
    for params, body, _ in vector_ctors(e, n):
        w(f"[MethodImpl(MethodImplOptions.AggressiveInlining)]")
        w(f"public {t}({params}) {{ {body} }}")
    w()
    # Conversions.
    w(f"public static implicit operator {t}({e} v) => new {t}(v);")
    for src in IMPLICIT[e]:
        w(f"public static implicit operator {t}({src} v) => new {t}(v);")
        w(f"public static implicit operator {t}({vt(src, n)} v) => new {t}(v);")
    for src in EXPLICIT[e]:
        w(f"public static explicit operator {t}({src} v) => new {t}(v);")
        w(f"public static explicit operator {t}({vt(src, n)} v) => new {t}(v);")
    w()

    def bin_ops(ops, result, both=True):
        for op in ops:
            r = result
            w(f"public static {r} operator {op}({t} lhs, {t} rhs) => new {r}({', '.join(f'lhs.{c} {op} rhs.{c}' for c in C[:n])});")
            w(f"public static {r} operator {op}({t} lhs, {e} rhs) => new {r}({', '.join(f'lhs.{c} {op} rhs' for c in C[:n])});")
            w(f"public static {r} operator {op}({e} lhs, {t} rhs) => new {r}({', '.join(f'lhs {op} rhs.{c}' for c in C[:n])});")

    b = vt("bool", n)
    if e == "bool":
        bin_ops(["==", "!="], b)
        bin_ops(["&", "|", "^"], t)
        w(f"public static {t} operator !({t} val) => new {t}({', '.join(f'!val.{c}' for c in C[:n])});")
    else:
        bin_ops(["+", "-", "*", "/", "%"], t)
        neg = "-val.{c}" if e != "uint" else "(uint)-val.{c}"
        w(f"public static {t} operator -({t} val) => new {t}({', '.join(neg.format(c=c) for c in C[:n])});")
        w(f"public static {t} operator +({t} val) => val;")
        w(f"public static {t} operator ++({t} val) => new {t}({', '.join(f'++val.{c}' for c in C[:n])});")
        w(f"public static {t} operator --({t} val) => new {t}({', '.join(f'--val.{c}' for c in C[:n])});")
        bin_ops(["<", "<=", ">", ">=", "==", "!="], b)
        if e in ("int", "uint"):
            bin_ops(["&", "|", "^"], t)
            w(f"public static {t} operator ~({t} val) => new {t}({', '.join(f'~val.{c}' for c in C[:n])});")
            w(f"public static {t} operator <<({t} x, int n) => new {t}({', '.join(f'x.{c} << n' for c in C[:n])});")
            w(f"public static {t} operator >>({t} x, int n) => new {t}({', '.join(f'x.{c} >> n' for c in C[:n])});")
    w()
    # Indexer.
    w(f"/// <summary>The component of the index (0 to {n - 1}).</summary>")
    w(f"public {e} this[int index]")
    w("{")
    w(f"    readonly get {{ if ((uint)index >= {n}u) throw new ArgumentException(\"index must be between[0...{n - 1}]\"); return Unsafe.Add(ref Unsafe.AsRef(in x), index); }}")
    w(f"    set {{ if ((uint)index >= {n}u) throw new ArgumentException(\"index must be between[0...{n - 1}]\"); Unsafe.Add(ref x, index) = value; }}")
    w("}")
    w()
    # Swizzles.
    for k in (2, 3, 4):
        for combo in itertools.product(C[:n], repeat=k):
            name = "".join(combo)
            st = vt(e, k)
            w("[EditorBrowsable(EditorBrowsableState.Never)]")
            getter = f"readonly get => new {st}({', '.join(combo)});"
            if len(set(combo)) == k:
                setter = " set { " + " ".join(f"{c} = value.{C[i]};" for i, c in enumerate(combo)) + " }"
                w(f"public {st} {name} {{ {getter}{setter} }}")
            else:
                w(f"public readonly {st} {name} => new {st}({', '.join(combo)});")
    w()
    # Equality and text.
    w(f"public readonly bool Equals({t} rhs) => {' && '.join(f'{c} == rhs.{c}' for c in C[:n])};")
    w(f"public override readonly bool Equals(object o) => o is {t} converted && Equals(converted);")
    w(f"public override readonly int GetHashCode() => (int)math.hash(this);")
    fmt = ", ".join(f"{{{i}}}{SUFFIX[e]}" for i in range(n))
    w(f"public override readonly string ToString() => string.Format(\"{t}({fmt})\", {', '.join(C[:n])});")
    if e != "bool":
        w(f"public readonly string ToString(string format, IFormatProvider formatProvider) =>")
        w(f"    string.Format(\"{t}({fmt})\", {', '.join(f'{c}.ToString(format, formatProvider)' for c in C[:n])});")
    w.close()
    w.depth -= 1
    w("}")
    # The constructors as functions of math.
    m = W()
    m.depth = 2
    for params, body, kind in vector_ctors(e, n):
        args = ", ".join(p.split(" ")[1] for p in params.split(", "))
        m(f"[MethodImpl(MethodImplOptions.AggressiveInlining)] public static {t} {t}({params}) => new {t}({args});")
    return w.text(), m.lines


