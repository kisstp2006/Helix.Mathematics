def matrix_ctors(e, r, c):
    t = mt(e, r, c)
    col = vt(e, r)
    out = []
    out.append((", ".join(f"{col} c{j}" for j in range(c)), " ".join(f"this.c{j} = c{j};" for j in range(c))))
    elems = [f"{e} m{i}{j}" for i in range(r) for j in range(c)]
    body = " ".join(f"this.c{j} = new {col}({', '.join(f'm{i}{j}' for i in range(r))});" for j in range(c))
    out.append((", ".join(elems), body))
    out.append((f"{e} v", " ".join(f"this.c{j} = v;" for j in range(c))))
    for src in IMPLICIT[e] + EXPLICIT[e]:
        if src == "half":
            continue
        out.append((f"{src} v", " ".join(f"this.c{j} = new {col}(v);" for j in range(c))))
        out.append((f"{mt(src, r, c)} v", " ".join(f"this.c{j} = new {col}(v.c{j});" for j in range(c))))
    return out


def matrix(e, r, c):
    t = mt(e, r, c)
    col = vt(e, r)
    w = W()
    w("using System;\nusing System.Diagnostics.CodeAnalysis;\nusing System.Runtime.CompilerServices;\n\nnamespace Helix.Mathematics\n{")
    w.depth += 1
    ifaces = f"IEquatable<{t}>" + ("" if e == "bool" else ", IFormattable")
    w(f"/// <summary>A matrix of {r} rows and {c} columns of {e} values, stored by columns.</summary>")
    w("[Serializable]")
    w.open(f"public partial struct {t} : {ifaces}")
    w(f"public {col} {', '.join(f'c{j}' for j in range(c))};")
    w()
    if e != "bool":
        if r == c:
            ident = ", ".join(f"new {col}({', '.join(ONE[e] if i == j else ZERO[e] for i in range(r))})" for j in range(c))
            w(f"/// <summary>The identity.</summary>")
            w(f"public static readonly {t} identity = new {t}({ident});")
        w(f"/// <summary>All elements zero.</summary>")
        w(f"public static readonly {t} zero;")
        w()
    for params, body in matrix_ctors(e, r, c):
        w(f"[MethodImpl(MethodImplOptions.AggressiveInlining)]")
        w(f"public {t}({params}) {{ {body} }}")
    w()
    w(f"public static implicit operator {t}({e} v) => new {t}(v);")
    for src in IMPLICIT[e]:
        if src == "half":
            continue
        w(f"public static implicit operator {t}({src} v) => new {t}(v);")
        w(f"public static implicit operator {t}({mt(src, r, c)} v) => new {t}(v);")
    for src in EXPLICIT[e]:
        w(f"public static explicit operator {t}({src} v) => new {t}(v);")
        w(f"public static explicit operator {t}({mt(src, r, c)} v) => new {t}(v);")
    w()
    b = mt("bool", r, c)

    def bin_ops(ops, result):
        for op in ops:
            w(f"public static {result} operator {op}({t} lhs, {t} rhs) => new {result}({', '.join(f'lhs.c{j} {op} rhs.c{j}' for j in range(c))});")
            w(f"public static {result} operator {op}({t} lhs, {e} rhs) => new {result}({', '.join(f'lhs.c{j} {op} rhs' for j in range(c))});")
            w(f"public static {result} operator {op}({e} lhs, {t} rhs) => new {result}({', '.join(f'lhs {op} rhs.c{j}' for j in range(c))});")

    if e == "bool":
        bin_ops(["==", "!="], b)
        bin_ops(["&", "|", "^"], t)
        w(f"public static {t} operator !({t} val) => new {t}({', '.join(f'!val.c{j}' for j in range(c))});")
    else:
        bin_ops(["+", "-", "*", "/", "%"], t)
        w(f"public static {t} operator -({t} val) => new {t}({', '.join(f'-val.c{j}' for j in range(c))});")
        w(f"public static {t} operator +({t} val) => val;")
        w(f"public static {t} operator ++({t} val) => new {t}({', '.join(f'++val.c{j}' for j in range(c))});")
        w(f"public static {t} operator --({t} val) => new {t}({', '.join(f'--val.c{j}' for j in range(c))});")
        bin_ops(["<", "<=", ">", ">=", "==", "!="], b)
        if e in ("int", "uint"):
            bin_ops(["&", "|", "^"], t)
            w(f"public static {t} operator ~({t} val) => new {t}({', '.join(f'~val.c{j}' for j in range(c))});")
            w(f"public static {t} operator <<({t} x, int n) => new {t}({', '.join(f'x.c{j} << n' for j in range(c))});")
            w(f"public static {t} operator >>({t} x, int n) => new {t}({', '.join(f'x.c{j} >> n' for j in range(c))});")
    w()
    w(f"/// <summary>The column of the index (0 to {c - 1}).</summary>")
    w(f"public ref {col} this[int index]")
    w("{")
    w(f"    [UnscopedRef] get {{ if ((uint)index >= {c}u) throw new ArgumentException(\"index must be between[0...{c - 1}]\"); return ref Unsafe.Add(ref c0, index); }}")
    w("}")
    w()
    w(f"public readonly bool Equals({t} rhs) => {' && '.join(f'c{j}.Equals(rhs.c{j})' for j in range(c))};")
    w(f"public override readonly bool Equals(object o) => o is {t} converted && Equals(converted);")
    w(f"public override readonly int GetHashCode() => (int)math.hash(this);")
    rows = []
    idx = 0
    for i in range(r):
        rows.append(", ".join(f"{{{i * c + j}}}{SUFFIX[e]}" for j in range(c)))
    fmt = ",  ".join(rows)
    elems = ", ".join(f"c{j}.{C[i]}" for i in range(r) for j in range(c))
    w(f"public override readonly string ToString() => string.Format(\"{t}({fmt})\", {elems});")
    if e != "bool":
        felems = ", ".join(f"c{j}.{C[i]}.ToString(format, formatProvider)" for i in range(r) for j in range(c))
        w(f"public readonly string ToString(string format, IFormatProvider formatProvider) =>")
        w(f"    string.Format(\"{t}({fmt})\", {felems});")
    w.close()
    w.depth -= 1
    w("}")
    m = W()
    m.depth = 2
    for params, body in matrix_ctors(e, r, c):
        args = ", ".join(p.split(" ")[1] for p in params.split(", "))
        m(f"[MethodImpl(MethodImplOptions.AggressiveInlining)] public static {t} {t}({params}) => new {t}({args});")
    return w.text(), m.lines


